import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {calculate} from '../assets/operations-models.js';
const root=path.resolve(import.meta.dirname,'..');
const tools=JSON.parse(fs.readFileSync(path.join(root,'data/operations-calculators.json'),'utf8'));
assert.equal(tools.length,8);assert.equal(new Set(tools.map(t=>t.slug)).size,8);
const inputs=t=>Object.fromEntries(t.fields.map(f=>[f.name,f.value]));
const amounts=(id,v)=>calculate(id,v).map(r=>r[1]);
const defaults=Object.fromEntries(tools.map(t=>[t.id,inputs(t)]));
const close=(a,b)=>{assert.equal(a.length,b.length);a.forEach((n,i)=>assert(Math.abs(n-b[i])<=1e-8*Math.max(1,Math.abs(b[i])),`${n} != ${b[i]}`));};
close(amounts('breakeven',defaults.breakeven),[50,100,100,8000]);
close(amounts('landed',defaults.landed),[200,200,1100,1080,5.5,5.4,20]);
close(amounts('weighted',defaults.weighted),[17,2600,400,3000,2600/17,3000/17]);
close(amounts('yield',defaults.yield),[80,200,2000,2.5]);
close(amounts('change',defaults.change),[480,980,196,1176]);
close(amounts('capacity',defaults.capacity),[32,42,35,7,82.03125]);
close(amounts('inventory',defaults.inventory),[145,62,60,-2]);
close(amounts('concentration',defaults.concentration),[25,10000,90000,10]);
close(amounts('breakeven',{...defaults.breakeven,fixed:5025}),[50,100.5,101,8080]);
close(amounts('breakeven',{...defaults.breakeven,fixed:0}),[50,0,0,0]);
close(amounts('landed',{...defaults.landed,packsB:4}),[200,100,1100,560,5.5,5.6,540]);
close(amounts('weighted',{...defaults.weighted,hours1:0,hours2:0,hours3:2,expenses:0}),[2,600,0,600,300,300]);
close(amounts('yield',{...defaults.yield,good:1000}),[100,0,2000,2]);
close(amounts('change',{...defaults.change,markup:0}),[480,980,0,980]);
close(amounts('capacity',{...defaults.capacity,demand:50}),[32,42,50,-8,117.1875]);
close(amounts('inventory',{...defaults.inventory,counted:62}),[145,62,62,0]);
close(amounts('inventory',{opening:0,receipts:0,returns:0,outgoing:0,removed:0,counted:0}),[0,0,0,0]);
close(amounts('concentration',{...defaults.concentration,risk:100}),[25,25000,75000,25]);
close(amounts('concentration',{...defaults.concentration,customer:0}),[0,0,100000,0]);
for(const [id,v] of Object.entries(defaults)){
 for(const k of Object.keys(v))for(const bad of [NaN,Infinity,-1,'',null])assert.throws(()=>calculate(id,{...v,[k]:bad}),`${id}.${k}=${bad}`);
 const t=tools.find(t=>t.id===id);for(const f of t.fields.filter(f=>f.step===1))assert.throws(()=>calculate(id,{...v,[f.name]:1.5}));
 const html=fs.readFileSync(path.join(root,'dist/operations-calculators',t.slug,'index.html'),'utf8');
 assert(html.includes('data-operations-calculator="'+id+'"')&&html.includes('aria-live="polite"')&&html.includes('<noscript>'));
 assert(html.includes('disabled>Calculate scenario')&&html.includes('type="module"'));
 assert(html.includes('https://businessownerindex.com/operations-calculators/'+t.slug+'/'));
 for(const f of t.fields)assert(html.includes('for="'+id+'-'+f.name+'"')&&html.includes('id="'+id+'-'+f.name+'"'));
 for(const s of t.related)assert(html.includes('/resources/'+s+'/'));
}
assert.throws(()=>calculate('breakeven',{...defaults.breakeven,price:30}));
assert.throws(()=>calculate('weighted',{...defaults.weighted,hours1:0,hours2:0,hours3:0}));
assert.throws(()=>calculate('yield',{...defaults.yield,good:1001}));
assert.throws(()=>calculate('yield',{...defaults.yield,good:0}));
assert.throws(()=>calculate('capacity',{...defaults.capacity,nonservice:40}));
assert.throws(()=>calculate('inventory',{...defaults.inventory,outgoing:200}));
assert.throws(()=>calculate('concentration',{...defaults.concentration,customer:100001}));
assert.throws(()=>calculate('concentration',{...defaults.concentration,risk:101}));
assert.throws(()=>calculate('concentration',{...defaults.concentration,total:0}));
assert.throws(()=>calculate('change',{...defaults.change,hours:1e308,rate:1e308}));
assert.throws(()=>calculate('inventory',{...defaults.inventory,opening:1e20}));
assert.throws(()=>calculate('not-a-tool',{}));
const hub=fs.readFileSync(path.join(root,'dist/operations-calculators/index.html'),'utf8');assert.equal((hub.match(/<article class="guide-card">/g)||[]).length,8);
const js=fs.readFileSync(path.join(root,'dist/assets/operations-calculators.js'),'utf8');assert(js.includes('operations-models.js?v=')&&js.includes("addEventListener('input',clear)")&&js.includes("addEventListener('change',clear)"));
assert(fs.readFileSync(path.join(root,'dist/calculators/index.html'),'utf8').includes('/operations-calculators/'));
console.log('PASS: eight operations calculators; independent default/edited arithmetic, boundary/invalid/overflow handling, unique hub links, related guides and external stale-clearing accessible client.');
